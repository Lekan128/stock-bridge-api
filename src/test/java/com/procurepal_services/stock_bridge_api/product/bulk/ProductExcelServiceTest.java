    private List<String> headersOf(byte[] file) {
        try (XSSFWorkbook workbook = open(file)) {
            List<String> headers = new ArrayList<>();
            Sheet data = workbook.getSheet("Products");
            for (Cell cell : (data == null ? workbook.getSheetAt(0) : data).getRow(0)) {
                headers.add(cell.getStringCellValue());
            }
            return headers;
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** Reads the validation records back out and maps each covered column to the range it points at. */
    private Map<String, String> dropdownRangesByColumn(XSSFSheet sheet, List<String> headers) {
        Map<String, String> byColumn = new java.util.LinkedHashMap<>();
        for (XSSFDataValidation validation : sheet.getDataValidations()) {
            String formula = validation.getValidationConstraint().getFormula1();
            for (int i = 0; i < validation.getRegions().countRanges(); i++) {
                int column = validation.getRegions().getCellRangeAddress(i).getFirstColumn();
                if (column >= 0 && column < headers.size()) {
                    byColumn.put(headers.get(column), formula);
                }
            }
        }
        return byColumn;
    }

    /** Resolves a defined name to the values sitting in the range it points at. */
    private List<String> valuesOfNamedRange(XSSFWorkbook workbook, String name) {
        Name definedName = workbook.getName(name);
        assertThat(definedName).as("defined name %s", name).isNotNull();
        org.apache.poi.ss.util.AreaReference area =
                new org.apache.poi.ss.util.AreaReference(definedName.getRefersToFormula(), workbook.getSpreadsheetVersion());
        Sheet sheet = workbook.getSheet(area.getFirstCell().getSheetName());
        List<String> values = new ArrayList<>();
        for (org.apache.poi.ss.util.CellReference reference : area.getAllReferencedCells()) {
            Row row = sheet.getRow(reference.getRow());
            Cell cell = row == null ? null : row.getCell(reference.getCol());
            if (cell != null) {
                values.add(cell.getStringCellValue());
            }
        }
        return values;
    }

    private String formatOfColumn(XSSFSheet sheet, int columnIndex) {
        return sheet.getColumnStyle(columnIndex).getDataFormatString();
    }

    private XSSFWorkbook open(byte[] file) {
        try {
            return new XSSFWorkbook(new ByteArrayInputStream(file));
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

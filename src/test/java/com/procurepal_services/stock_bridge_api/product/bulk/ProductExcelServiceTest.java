/**
 * The product template and its parser, tested against each other and against the written file
 * itself. No Spring: {@link ProductExcelService} takes one collaborator, and constructing it
 * directly keeps these fast enough to run on every save.
 *
 * <h2>Why several of these read the generated bytes back with POI</h2>
 * A data validation that silently failed to attach is invisible to a test that checks cell values -
 * the file opens, the columns are right, the examples are there, and the dropdown the whole feature
 * was for simply is not. It is the classic failure of generating spreadsheets, and the only way to
 * catch it is to read the validation records out of the written file and assert on them, which is
 * what {@link #everyIntendedColumnReallyHasADropdownInTheWrittenFile} does.
 */
